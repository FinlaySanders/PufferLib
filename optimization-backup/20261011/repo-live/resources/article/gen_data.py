#!/usr/bin/env python3
# Chart adapter; certificates/ is the sole source of fixed-model results.
import os, statistics as st, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent / "certificates"))
import ledger
# Preserve the user-edited results narrative while validating its underlying data.
md_path = ledger.ROOT / 'RESULTS.md'
md_before = md_path.read_bytes() if md_path.exists() else None
try:
    canonical = ledger.build()
finally:
    if md_before is not None:
        md_path.write_bytes(md_before)
article = Path(__file__).resolve().parent
# These baseline constants are retained from the draft; primary-source verification
# is outstanding. They are not certified by the fixed-model results ledger.
AUTOASCEND = {"2021 median": 5336, "2023 median": 4918, "2023 mean": 8556}
measured_aa = json.loads((article / "autoascend/results/summary.json").read_text())
assert measured_aa["attempt_set_complete"] and measured_aa["attempts_recorded"] == 8064
out = {"autoascend": AUTOASCEND, "autoascend_measured": measured_aa, "autoascend_status": "local measured baseline; published references retained",
       "snapshot_utc": canonical["snapshot_utc"], "manifest_sha256": canonical["manifest_sha256"],
       "gens": canonical["gens"]}
(article / "results.json").write_text(json.dumps(out, indent=2) + "\n")
(article / "results.csv").write_bytes((ledger.ROOT / "results.csv").read_bytes())
pending = [f"{g}/{i}" for g, interfaces in out["gens"].items()
           for i, group in interfaces.items() if group["pooled"] is None]
if pending:
    raise SystemExit("Figures not regenerated: incomplete headline certificates: " + ", ".join(pending)
                     + ". See certificates/RESULTS.md; existing images are older snapshots.")
manifest = json.loads((ledger.ROOT / "manifest.json").read_text())
EP = str(ledger.ROOT)
runs = {g: {i: [(r["id"], r["files"][0]["path"]) for r in manifest["runs"]
                if r["size"] == g and r["interface"] == i and r["cohort"] == "headline"]
            for i in ("fork", "stock")} for g in ledger.LANES}
rows = (ledger.ROOT / "results.csv").read_text().splitlines()
# C header: pooled mean/se/median per gen x interface (+ per-run medians/means), gym pooled, autoascend, quantile curves
G = ["1B","2B","4B"]; I = ["fork","stock","gym"]
h = ["// generated by resources/article/gen_data.py from the certified .ep logs -- do not edit", "#define N_GEN 3", "#define N_IF 3", "#define N_Q 64",
     'static const char* GEN_LABEL[N_GEN] = {"1B","2B","4B"};', 'static const char* IF_LABEL[N_IF] = {"fork engine","stock NLE","NetHackChallenge-v0"};',
     f"static const float AA_MEDIAN_2021 = {AUTOASCEND['2021 median']:.1f}f, AA_MEDIAN_2023 = {AUTOASCEND['2023 median']:.1f}f, AA_MEAN_2023 = {AUTOASCEND['2023 mean']:.1f}f;"]
h.append(f"static const float AA_MEDIAN = {measured_aa['median']:.6f}f, AA_MEAN = {measured_aa['mean']:.6f}f;")
def arr(name, f):
    h.append(f"static const float {name}[N_GEN][N_IF] = {{" + ", ".join("{" + ", ".join(f"{f(out['gens'][g][i]['pooled']):.1f}f" for i in I) + "}" for g in G) + "};")
arr("MEAN", lambda p: p["mean"]); arr("SE", lambda p: p.get("se", 0.0)); arr("MEDIAN", lambda p: p["median"])
arr("P10", lambda p: p["p10"]); arr("P25", lambda p: p["p25"]); arr("P75", lambda p: p["p75"]); arr("P90", lambda p: p["p90"]); arr("NGAMES", lambda p: p["n"])
h.append("#define MAX_RUNS 4")
h.append("static const int N_RUNS[N_GEN][N_IF] = {" + ", ".join("{" + ", ".join(str(len(out['gens'][g][i]['runs'])) for i in I) + "}" for g in G) + "};")
for nm, key in (("RUN_MEDIAN","median"),("RUN_MEAN","mean")):
    h.append(f"static const float {nm}[N_GEN][N_IF][MAX_RUNS] = {{" + ", ".join("{" + ", ".join("{" + ", ".join(f"{d[key]:.1f}f" for d in (out['gens'][g][i]['runs'] + [dict(median=0,mean=0)]*4)[:4]) + "}" for i in I) + "}" for g in G) + "};")
h.append("static const float QUANT[N_GEN][2][N_Q] = {" + ", ".join("{" + ", ".join("{" + ", ".join(f"{float(v):.1f}f" for v in out['gens'][g][i]['pooled']['quant']) + "}" for i in ("fork","stock")) + "}" for g in G) + "};")
# per-role stats from the fork logs (col 4 = role index, NetHack order Arc..Wiz)
ROLES=["Archeologist","Barbarian","Caveman","Healer","Knight","Monk","Priest","Rogue","Ranger","Samurai","Tourist","Valkyrie","Wizard"]
def ep_rows(path): return [l.split() for l in open(path) if l.strip()][4000:14000]
h.append("#define N_ROLE 13")
h.append("static const char* ROLE_NAME[N_ROLE] = {" + ", ".join(f'"{r}"' for r in ROLES) + "};")
rm=[];rmean=[];rn=[]
for g in G:
    rr=sum((ep_rows(os.path.join(EP,f)) for _,f in runs[g]["fork"]),[])
    med=[];mean=[];n=[]
    for r in range(13):
        sc=[int(x[0]) for x in rr if int(x[4])==r]
        med.append(st.median(sc) if sc else 0); mean.append(sum(sc)/len(sc) if sc else 0); n.append(len(sc))
    rm.append(med); rmean.append(mean); rn.append(n)
for nm,arr in (("ROLE_MEDIAN",rm),("ROLE_MEAN",rmean),("ROLE_N",rn)):
    h.append(f"static const float {nm}[N_GEN][N_ROLE] = {{" + ", ".join("{" + ", ".join(f"{float(v):.1f}f" for v in row) + "}" for row in arr) + "};")
# Overnight depth-trained policies, evaluated on the fork engine.
depth_roles = json.loads((article / "depth_policy_role_results.json").read_text())
assert depth_roles["cohort"] == "depth-trained" and depth_roles["steps"] == "2B"
assert depth_roles["interface"] == "fork" and len(depth_roles["seeds"]) == 8
assert sum(r["n"] for r in depth_roles["roles"]) == depth_roles["n"] == 80000
assert [r["role"] for r in depth_roles["roles"]] == ROLES
for nm, key in (("ROLE_DEPTH_MEAN", "mean"), ("ROLE_DEPTH_MEDIAN", "median")):
    h.append(f"static const float {nm}[N_ROLE] = {{" + ", ".join(f"{r[key]:.6f}f" for r in depth_roles["roles"]) + "};")
# score vs deepest level: 4B fork logs (20K games), per-depth stats + a deterministic subsample of points
rr=sum((ep_rows(os.path.join(EP,f)) for _,f in runs["4B"]["fork"]),[])
pts=[(int(x[7]), int(x[0])) for x in rr]
maxd=max(d for d,_ in pts)
h.append(f"#define MAX_DEPTH {maxd}")
dn=[];dmed=[];d25=[];d75=[]
for d in range(1,maxd+1):
    sc=sorted(v for dd,v in pts if dd==d)
    dn.append(len(sc)); dmed.append(st.median(sc) if sc else 0)
    d25.append(sc[int(.25*len(sc))] if sc else 0); d75.append(sc[min(len(sc)-1,int(.75*len(sc)))] if sc else 0)
for nm,arr in (("DEPTH_N",dn),("DEPTH_MED",dmed),("DEPTH_P25",d25),("DEPTH_P75",d75)):
    h.append(f"static const float {nm}[MAX_DEPTH] = {{" + ", ".join(f"{float(v):.1f}f" for v in arr) + "};")
best=max(pts,key=lambda t:t[1]); deep=max(pts,key=lambda t:(t[0],t[1]))
h.append(f"static const int BEST_DEPTH = {best[0]}, BEST_SCORE = {best[1]}, DEEP_DEPTH = {deep[0]}, DEEP_SCORE = {deep[1]}, N_GAMES_4B = {len(pts)};")
import random; random.seed(7); sub=random.sample(pts, 8000)
h.append(f"#define N_PTS {len(sub)}")
h.append("static const unsigned char PT_DEPTH[N_PTS] = {" + ",".join(str(d) for d,_ in sub) + "};")
h.append("static const int PT_SCORE[N_PTS] = {" + ",".join(str(v) for _,v in sub) + "};")
# depth vs training size (fork logs): mean deepest level, share of games reaching Dlvl 8+/10+, mean game turns
dm=[];g8=[];g10=[];tm=[]
for g in G:
    rr=sum((ep_rows(os.path.join(EP,f)) for _,f in runs[g]["fork"]),[])
    d=[int(x[7]) for x in rr]; t=[int(x[8]) for x in rr]
    dm.append(sum(d)/len(d)); g8.append(100*sum(1 for v in d if v>=8)/len(d)); g10.append(100*sum(1 for v in d if v>=10)/len(d)); tm.append(sum(t)/len(t))
for nm,arr in (("GEN_DEPTH_MEAN",dm),("GEN_PCT_DLVL8",g8),("GEN_PCT_DLVL10",g10),("GEN_TURNS_MEAN",tm)):
    h.append(f"static const float {nm}[N_GEN] = {{" + ", ".join(f"{float(v):.3f}f" for v in arr) + "};")
open("resources/article/results_data.h","w").write("\n".join(h)+"\n")
print("\n".join(rows))
